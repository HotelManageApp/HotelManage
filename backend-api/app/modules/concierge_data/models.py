"""Knowledge base entries and nearby places (spec/SPEC-concierge-guide.md, "Dữ liệu").

`search_tsv` is generated by PostgreSQL from both languages, accent-free (`f_unaccent`, an
IMMUTABLE wrapper around `unaccent` created by migration 0008), so "an sang" finds "ăn sáng".
"""

import enum
import uuid
from datetime import datetime
from decimal import Decimal
from typing import Any

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    Computed,
    DateTime,
    Enum,
    ForeignKey,
    Index,
    Numeric,
    Text,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, TSVECTOR, UUID
from sqlalchemy.orm import Mapped, mapped_column

from app.core.db import Base, TimestampMixin


class KbTopic(enum.StrEnum):
    BREAKFAST = "BREAKFAST"
    FACILITIES = "FACILITIES"
    SERVICES = "SERVICES"
    POLICIES = "POLICIES"
    WIFI = "WIFI"
    TRANSPORT = "TRANSPORT"
    OTHER = "OTHER"


class PlaceCategory(enum.StrEnum):
    ATTRACTION = "ATTRACTION"
    FOOD_NEARBY = "FOOD_NEARBY"
    TRANSPORT = "TRANSPORT"
    SHOPPING = "SHOPPING"
    HEALTH = "HEALTH"


def _tsv(weighted: dict[str, list[str]]) -> str:
    """SQL for a weighted, accent-free tsvector over the given columns."""
    parts = []
    for weight, columns in weighted.items():
        joined = " || ' ' || ".join(f"coalesce({c}, '')" for c in columns)
        parts.append(f"setweight(to_tsvector('simple', f_unaccent({joined})), '{weight}')")
    return " || ".join(parts)


KB_TSV = _tsv({"A": ["title_vi", "title_en"], "B": ["content_vi", "content_en"]})
PLACE_TSV = _tsv({"A": ["name"], "B": ["description_vi", "description_en"]})


def _enum(cls: type[enum.StrEnum], name: str) -> Enum:
    return Enum(cls, name=name, values_callable=lambda e: [m.value for m in e])


class KbEntry(TimestampMixin, Base):
    __tablename__ = "kb_entry"
    __table_args__ = (Index("ix_kb_entry_search_tsv", "search_tsv", postgresql_using="gin"),)

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    topic: Mapped[KbTopic] = mapped_column(_enum(KbTopic, "kb_topic"), nullable=False, index=True)
    title_vi: Mapped[str] = mapped_column(Text, nullable=False)
    title_en: Mapped[str] = mapped_column(Text, nullable=False)
    content_vi: Mapped[str] = mapped_column(Text, nullable=False)
    content_en: Mapped[str] = mapped_column(Text, nullable=False)
    is_published: Mapped[bool] = mapped_column(Boolean, nullable=False, server_default=text("true"))
    search_tsv: Mapped[str] = mapped_column(TSVECTOR, Computed(KB_TSV, persisted=True))
    updated_by: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("staff.id", ondelete="SET NULL")
    )

    def title(self, lang: str) -> str:
        return self.title_vi if lang == "vi" else self.title_en

    def content(self, lang: str) -> str:
        return self.content_vi if lang == "vi" else self.content_en


class NearbyPlace(TimestampMixin, Base):
    __tablename__ = "nearby_place"
    __table_args__ = (Index("ix_nearby_place_search_tsv", "search_tsv", postgresql_using="gin"),)

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    category: Mapped[PlaceCategory] = mapped_column(
        _enum(PlaceCategory, "place_category"), nullable=False, index=True
    )
    name: Mapped[str] = mapped_column(Text, nullable=False)
    description_vi: Mapped[str | None] = mapped_column(Text)
    description_en: Mapped[str | None] = mapped_column(Text)
    distance_km: Mapped[Decimal | None] = mapped_column(Numeric(5, 2))
    open_hours: Mapped[str | None] = mapped_column(Text)
    map_url: Mapped[str | None] = mapped_column(Text)
    is_published: Mapped[bool] = mapped_column(Boolean, nullable=False, server_default=text("true"))
    search_tsv: Mapped[str] = mapped_column(TSVECTOR, Computed(PLACE_TSV, persisted=True))
    updated_by: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("staff.id", ondelete="SET NULL")
    )

    def description(self, lang: str) -> str | None:
        return self.description_vi if lang == "vi" else self.description_en


class ChatMessage(Base):
    """One line of the concierge chat. History belongs to the stay (every device sees it) and is
    deleted when the stay closes (personal data, chatbot-tools-spec §1)."""

    __tablename__ = "chat_message"
    __table_args__ = (
        Index("ix_chat_message_stay_created", "stay_id", "created_at"),
        CheckConstraint("role IN ('GUEST', 'ASSISTANT')", name="role_known"),
        # A retried send from ai-service carries the same client_message_id: stored once.
        UniqueConstraint("stay_id", "client_message_id", "role", name="uq_chat_message_client_id"),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    stay_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("stay.id", ondelete="CASCADE"), nullable=False
    )
    session_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("stay_session.id", ondelete="CASCADE"), nullable=False
    )
    client_message_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True))
    role: Mapped[str] = mapped_column(Text, nullable=False)  # GUEST | ASSISTANT
    content: Mapped[str] = mapped_column(Text, nullable=False)
    # Tool names, arguments and KB ids used for the answer; never tokens.
    tool_trace: Mapped[Any | None] = mapped_column(JSONB(none_as_null=True))
    grounded: Mapped[bool | None] = mapped_column(Boolean)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.clock_timestamp(), nullable=False
    )
